export const MAGIC = [...SIGNS, ...REFERENCE_MAGIC];

export function magicInfo(key) {
  return MAGIC.find((entry) => entry.key === (typeof key === 'string' ? key : key?.key)) ?? null;
}

function escapeHtml(value) {
  return String(value ?? '').replace(
    /[&<>"']/g,
    (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[character]
  );
}

export function magicItemData(value) {
  const entry = typeof value === 'string' ? magicInfo(value) : value;
  if (!entry?.key || !entry?.name) throw new Error('A known magic entry is required');
  const { name, source, page, text, ...magic } = structuredClone(entry);
  const cost =
    magic.cost.text ??
    (magic.cost.options.length
      ? magic.cost.options.join(' / ')
      : magic.cost.min === magic.cost.max
        ? magic.cost.min
        : `${magic.cost.min}–${magic.cost.max}`);
  const labels = {
    dodge: 'Dodge',
    block: 'Block',
    resistMagic: 'Resist Magic',
    spellCasting: 'Spell Casting',
    reposition: 'Reposition',
    willTriple: 'Target WILL × 3',
    gmDC: 'GM-selected DC',
    variable: 'See effect',
  };
  const defenses =
    magic.defenseText ??
    (magic.defenses.length ? magic.defenses.map((key) => labels[key] ?? key).join(' or ') : 'None');
  const ritual = magic.ritual
    ? `<p><strong>Preparation:</strong> ${escapeHtml(magic.ritual.preparation)}. <strong>Ritual Crafting DC:</strong> ${escapeHtml(magic.ritual.dc)}.</p><p><strong>Components:</strong> ${escapeHtml(magic.ritual.components)}${magic.ritual.alternateComponents ? `. Alternative: ${escapeHtml(magic.ritual.alternateComponents)}` : ''}.</p>`
    : '';
  return {
    name,
    type: 'magic',
    img: 'icons/svg/book.svg',
    system: {
      magic,
      source,
      page,
      quantity: 1,
      weight: 0,
      cost: 0,
      equipped: false,
      carried: false,
      category: magic.kind,
      effectText: text,
      description: `<p>${escapeHtml(text)}</p><p><strong>STA:</strong> ${escapeHtml(cost)}. <strong>Range:</strong> ${escapeHtml(magic.range.text)}. <strong>Duration:</strong> ${escapeHtml(magic.duration.text)}. <strong>Defense:</strong> ${escapeHtml(defenses)}.</p>${ritual}<p>Source: ${escapeHtml(source)}, p.${escapeHtml(page)}.</p>`,
    },
  };
}
